    private static readonly Lazy<IReadOnlyList<WisdomEntry>> Entries = new(BuildEntries);

    public static int Count => Entries.Value.Count;

    public static WisdomEntry RandomEntry(WisdomEntry? except = null)
    {
        var list = Entries.Value;
        WisdomEntry selected;
        do selected = list[Random.Shared.Next(list.Count)];
        while (list.Count > 1 && selected == except);
        return selected;
    }

    private static IReadOnlyList<WisdomEntry> BuildEntries()
    {
        var entries = new List<WisdomEntry>(Sources.Length * Applications.Length);
        foreach (var source in Sources)
        {
            for (var index = 0; index < Applications.Length; index++)
            {
                entries.Add(new WisdomEntry(
                    $"{source.CoreReflection} {Applications[index]}",
                    source.Name,
                    source.Reference,
                    $"{source.Name} {source.Reference} {source.Practice}"));
            }
        }
        return entries;
    }
